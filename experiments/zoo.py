"""Build the regression zoo: deliberate edits to two prompts, each one a suite.

    python experiments/zoo.py

writes experiments/zoo.toml and the prompt and target files under experiments/zoo/. Each
variant records what the edit was *meant* to be. What it turned out to be is measured on
the full dataset by proof.py, and the two do not always agree.
"""

from __future__ import annotations

import json
import random
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any

from tripwire import datasets

HERE = Path(__file__).parent
PROMPTS, DATA = HERE.parent / "prompts", HERE.parent / "datasets"
HARMFUL, HARMLESS, HELPFUL, SWAP = "harmful", "harmless", "helpful", "model swap"

GUARDRAILS = """
[suite.{name}.guardrails]
output_tokens_ratio_max = 1.25
latency_p95_ratio_max   = 1.50
truncation_rate_max     = 0.01
error_rate_max          = 0.02
"""

HEADER = """# Generated by experiments/zoo.py; edit that, not this.
# Run with:  tripwire queue -c experiments/zoo.toml --match "zoo-*"
db = "../tripwire.db"

[provider.local-openai]   # the same Ollama server, through its OpenAI-compatible API
kind     = "openai_compat"
base_url = "http://localhost:11434/v1"

[judge]
model    = "qwen2.5:7b"
system   = "../prompts/judge/system.md"
template = "../prompts/judge/user.md"
rubric   = "../prompts/judge/rubric.toml"
"""


@dataclass
class Variant:
    name: str
    intent: str  # what the edit was meant to be: HARMFUL, HARMLESS, SWAP or "baseline"
    what: str  # one line for the report
    system: str | Path | None = None  # new prompt text, an existing file, or the baseline's
    template: str | None = None
    reps: int = 1
    settings: dict[str, Any] = field(default_factory=dict)  # target fields that differ


@dataclass
class Task:
    key: str
    dataset: str
    prompts: str  # folder under prompts/ holding the baseline system.md and user.md
    target: dict[str, Any]
    suite: str  # extra lines for every suite of this task
    metrics: list[str]  # the first one is the suite's primary metric
    variants: list[Variant]

    @property
    def baseline(self) -> str:
        return self.variants[0].name


def parse(text: str) -> tuple[list[str], list[str], list[tuple[str, str]]]:
    """The Banking77 system prompt as instruction lines, labels and few-shot examples."""
    head, rest = text.split("\n\nIntents:\n")
    listed, _, shots = rest.partition("\nExamples:\n\n")
    examples = [
        (message.removeprefix("Message: "), label)
        for message, label in (e.split("\nIntent: ") for e in shots.strip().split("\n\n"))
    ]
    return head.splitlines(), [line[2:] for line in listed.splitlines()], examples


def build(
    lines: list[str],
    labels: list[str],
    examples: list[tuple[str, str]],
    heading: str = "{}:",
    bullet: str = "- ",
    fields: tuple[str, str] = ("Message", "Intent"),
) -> str:
    text = "\n".join(lines) + "\n\n" + heading.format("Intents") + "\n"
    text += "".join(f"{bullet}{label}\n" for label in labels)
    if examples:
        text += "\n" + heading.format("Examples") + "\n"
        text += "".join(f"\n{fields[0]}: {m}\n{fields[1]}: {label}\n" for m, label in examples)
    return text


def shuffled[T](items: list[T], seed: str) -> list[T]:
    """A fixed shuffle with its own generator, so adding a variant never reshuffles another."""
    return random.Random(seed).sample(items, len(items))


def banking() -> Task:
    folder = PROMPTS / "banking_intent"
    base = (folder / "system.md").read_text(encoding="utf-8")
    lines, labels, shots = parse(base)
    assert build(lines, labels, shots) == base, "the parser no longer matches the prompt"

    shown = {label for _, label in shots}
    dropped = shuffled([x for x in labels if x not in shown], "drop")[:10]
    # Each example takes the label of the example two places on: always a different one.
    wrong = [(m, shots[(i + 2) % len(shots)][1]) for i, (m, _) in enumerate(shots)]
    assert all(a[1] != b[1] for a, b in zip(shots, wrong, strict=True))
    # Extra examples come from the dev split, which exists for prompt work and shares no
    # case with the reference split the zoo is measured on. One per intent not yet shown.
    unseen: dict[str, str] = {}
    for case in shuffled(datasets.load(DATA / "banking77/dev.jsonl"), "dev"):
        if case.expected not in shown:
            unseen.setdefault(case.expected, case.input["text"])
    extra = [(text, label) for label, text in unseen.items()][:48]
    longer = build(lines, labels, shots + extra)
    polite = "Thank you for helping our support team with this task."
    sentence = "Answer in a complete sentence that explains your choice."
    reworded = [
        "You classify the intent of messages sent to a retail banking app.",
        "Look at the customer's message and answer with precisely one intent label from the "
        "following list.",
        "Give just the label: no explanation, no punctuation and no quotation marks.",
    ]

    def edit(name: str, intent: str, what: str, system: str | Path, reps: int = 1) -> Variant:
        return Variant(name, intent, what, system, reps=reps)

    def setting(name: str, intent: str, what: str, **settings: Any) -> Variant:
        return Variant(name, intent, what, settings=settings)

    variants = [
        Variant("zoo-baseline", "baseline", "The prompt as shipped", reps=2),
        # Meant to hurt.
        edit(
            "zoo-no-examples",
            HARMFUL,
            "All 16 few-shot examples removed",
            folder / "system_zero_shot.md",
            reps=2,
        ),
        edit(
            "zoo-half-examples",
            HARMFUL,
            "8 of the 16 few-shot examples removed",
            build(lines, labels, shots[:8]),
        ),
        edit(
            "zoo-mislabelled-4",
            HARMFUL,
            "4 of the 16 examples given a wrong label",
            build(lines, labels, [wrong[i] if i % 4 == 0 else s for i, s in enumerate(shots)]),
        ),
        edit(
            "zoo-mislabelled-16",
            HARMFUL,
            "All 16 examples given a wrong label",
            build(lines, labels, wrong),
        ),
        *(
            edit(
                f"zoo-drop-{k}-intents",
                HARMFUL,
                f"{k} of the 77 intents removed from the label list",
                build(lines, [x for x in labels if x not in dropped[:k]], shots),
                reps=2 if k == 5 else 1,
            )
            for k in (2, 5, 10)
        ),
        *(
            Variant(
                f"zoo-truncate-{k}",
                HARMFUL,
                f"Customer message cut to its first {k} characters",
                template=f"Message: {{text:.{k}}}\nIntent:",
            )
            for k in (60, 40, 25)
        ),
        setting("zoo-short-output", HARMFUL, "Output limit cut from 32 tokens to 4", max_tokens=4),
        edit(
            "zoo-conflicting-format",
            HARMFUL,
            f'An added instruction: "{sentence}"',
            build([*lines, sentence], labels, shots),
        ),
        setting("zoo-warm", HARMFUL, "Temperature raised from 0.7 to 1.0", temperature=1.0),
        setting("zoo-hot", HARMFUL, "Temperature raised from 0.7 to 1.5", temperature=1.5),
        # The same longer prompt twice: once where it fits, once where it does not.
        edit(
            "zoo-more-examples",
            HELPFUL,
            f"{len(extra)} more few-shot examples, taken from the dev split",
            longer,
        ),
        Variant(
            "zoo-more-examples-overflow",
            HARMFUL,
            "The same longer prompt with the context window at 2048 tokens: it no longer fits",
            longer,
            settings={"num_ctx": 2048, "allow_overflow": True},
        ),
        # Meant to change nothing.
        setting(
            "zoo-half-context",
            HARMLESS,
            "Context window halved to 2048 tokens; the prompt still fits",
            num_ctx=2048,
        ),
        edit(
            "zoo-whitespace",
            HARMLESS,
            "Markdown headings, star bullets, same words",
            build(lines, labels, shots, heading="## {}\n", bullet="* "),
        ),
        edit(
            "zoo-reorder-instructions",
            HARMLESS,
            "Second and third instruction swapped",
            build([lines[0], lines[2], lines[1]], labels, shots),
        ),
        edit(
            "zoo-synonyms",
            HARMLESS,
            "Instructions reworded with synonyms",
            build(reworded, labels, shots),
        ),
        Variant(
            "zoo-relabel-fields",
            HARMLESS,
            '"Message:" and "Intent:" renamed to "Customer:" and "Label:" throughout',
            build(lines, labels, shots, fields=("Customer", "Label")),
            "Customer: {text}\nLabel:",
        ),
        edit(
            "zoo-reorder-examples",
            HARMLESS,
            "Few-shot examples shuffled",
            build(lines, labels, shuffled(shots, "examples")),
        ),
        edit(
            "zoo-reorder-labels",
            HARMLESS,
            "Label list shuffled",
            build(lines, shuffled(labels, "labels"), shots),
            reps=2,
        ),
        edit(
            "zoo-polite-preamble",
            HARMLESS,
            "A sentence of thanks added at the top",
            build([polite, *lines], labels, shots),
        ),
        setting("zoo-salt", HARMLESS, "Identical configuration, forced to run again", salt="aa"),
        setting(
            "zoo-openai-endpoint",
            HARMLESS,
            "Same model through the OpenAI-compatible endpoint",
            provider="local-openai",
        ),
        # Another model altogether. Named swap-* so the zoo-* pattern stays on one model.
        setting("swap-gemma-1b", SWAP, "gemma3:1b in place of gemma3:4b", model="gemma3:1b"),
        setting("swap-qwen", SWAP, "qwen2.5:7b in place of gemma3:4b", model="qwen2.5:7b"),
    ]
    target = {"model": "gemma3:4b", "temperature": 0.7, "num_ctx": 4096, "max_tokens": 32}
    dataset = "datasets/banking77/reference.jsonl"
    return Task("banking", dataset, "banking_intent", target, "", ["exact.pass"], variants)


def policy_qa() -> Task:
    folder = PROMPTS / "policy_qa"
    role, blank, rules, abstain = (folder / "system.md").read_text(encoding="utf-8").splitlines()
    variants = [
        Variant("qa-baseline", "baseline", "The prompt as shipped", reps=2),
        Variant(
            "qa-no-abstain",
            HARMFUL,
            'The "say so if the documents do not cover it" instruction removed',
            folder / "system_no_abstain.md",
        ),
        Variant(
            "qa-no-grounding",
            HARMFUL,
            'The "use only the policy documents" instruction removed',
            "\n".join([role, blank, "Answer in one or two sentences.", abstain]) + "\n",
        ),
        Variant(
            "qa-hot", HARMFUL, "Temperature raised from 0.7 to 1.5", settings={"temperature": 1.5}
        ),
        Variant(
            "qa-reworded",
            HARMLESS,
            "Instructions reworded with synonyms",
            "You respond to customers' questions for a retail company.\n\n"
            "Rely solely on the policy documents in the message. Reply in one or two sentences.\n"
            "If the answer is not in the documents, say that they do not cover it. "
            "Do not guess.\n",
        ),
    ]
    target = {"model": "gemma3:4b", "temperature": 0.7, "num_ctx": 2048, "max_tokens": 120}
    suite = 'scorers        = ["fact", "judge"]\nprimary_metric = "judge.correct"\n'
    metrics = ["judge.correct", "judge.grounded"]
    dataset = "datasets/policy_qa/qa.jsonl"
    return Task("policy_qa", dataset, "policy_qa", target, suite, metrics, variants)


def tasks() -> list[Task]:
    return [banking(), policy_qa()]


def write(root: Path = HERE) -> None:
    """Write zoo.toml and the zoo/ folder under `root`. The paths inside them assume it is
    experiments/, where the tests check that what is committed is what this writes."""
    out = root / "zoo"
    out.mkdir(exist_ok=True)
    for old in out.iterdir():
        old.unlink()
    config = HEADER
    for task in tasks():
        for v in task.variants:
            paths = {}
            for kind, text in (("system", v.system), ("user", v.template)):
                if isinstance(text, str):
                    (out / f"{v.name}.{kind}.md").write_text(text, encoding="utf-8", newline="\n")
                    paths[kind] = f"zoo/{v.name}.{kind}.md"
                else:
                    source = text or PROMPTS / task.prompts / f"{kind}.md"
                    paths[kind] = "../" + source.relative_to(HERE.parent).as_posix()
            fields = {
                "kind": "prompt",
                "provider": "local",
                "system": paths["system"],
                "template": paths["user"],
                **task.target,
                **v.settings,
            }
            body = "".join(f"{key} = {json.dumps(value)}\n" for key, value in fields.items())
            (out / f"{v.name}.toml").write_text(body, encoding="utf-8", newline="\n")
            config += f'\n[suite.{v.name}]\ndataset = "../{task.dataset}"\n'
            config += f'target  = "zoo/{v.name}.toml"\n{task.suite}'
            config += f"reps    = {v.reps}\n" if v.reps > 1 else ""
            if v.intent in (SWAP, "baseline") and task.key == "banking":
                config += GUARDRAILS.format(name=v.name)  # shown by `tripwire compare`
    (root / "zoo.toml").write_text(config, encoding="utf-8", newline="\n")
    print(f"{sum(len(t.variants) for t in tasks())} suites written to {root / 'zoo.toml'}")


if __name__ == "__main__":
    write()
